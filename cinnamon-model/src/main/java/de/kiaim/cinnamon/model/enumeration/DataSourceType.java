package de.kiaim.cinnamon.model.enumeration;

/**
 * Enumeration representing different types of data sources.
 *
 * @author Daniel Preciado-Marquez
 */
public enum DataSourceType {
	/**
	 * Files are stored locally on the user's machine and directly uploaded.
	 */
	LOCAL,
	/**
	 * Files are fetched from a remote server.
	 */
	SERVER,
}
